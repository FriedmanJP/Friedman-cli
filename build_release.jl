# --- Step 4: Build standalone app via PackageCompiler.create_app() ---
# --strip-metadata: size win when StructUtils/JSON3 path stays healthy (F47).
# Do NOT add --strip-ir (MissingCodeError) or filter_stdlibs=true (requires
# incremental=false, rebuilding Base from scratch).
#
# -O1: cuts LLVM codegen time and peak RAM substantially during --output-o
# without hurting runtime latency (econometric kernels live in -O3 JLLs and
# runtime JIT still uses -O2).
#
# compress_sysimage=true (default; override via FRIEDMAN_COMPRESS_SYSIMAGE=false):
# cuts unpacked footprint by ~60% (~1.0 GiB -> ~400 MB) and keeps Windows well
# below the 2 GiB PE/DLL loader limit.
#
# JULIA_IMAGE_THREADS: PackageCompiler's --threads=1 only limits Julia task
# threads, not parallel LLVM image codegen threads. On runners with <24 GiB RAM
# (7 GiB macos-latest, 15-16 GiB ubuntu/windows-latest), parallel LLVM codegen
# spills into swap. Default to 1 thread on <24 GiB hosts unless overridden.
#
# include_transitive_dependencies=false + include_lazy_artifacts=false:
# `using Friedman` loads all required packages + extensions and bundles all
# active JLL artifacts (~50 MB) without dragging in unused lazy artifacts such
# as MKL_jll, oneTBB_jll, or IntelOpenMP_jll.
#
# cpu_target: Julia PackageCompiler defaults to "sysimage" (three clones on
# x86_64). One portable clone fits: x86_64 uses "generic", aarch64 uses "apple-m1".
const _CPU_TARGET = get(ENV, "FRDC_CPU_TARGET",
                        get(ENV, "FRIEDMAN_CPU_TARGET",
                            Sys.ARCH === :x86_64 ? "generic" : "apple-m1"))
const _COMPRESS_SYSIMAGE = lowercase(strip(get(ENV, "FRDC_COMPRESS_SYSIMAGE",
                                               get(ENV, "FRIEDMAN_COMPRESS_SYSIMAGE", "true")))) in ("1", "true", "yes", "on")
if !haskey(ENV, "JULIA_IMAGE_THREADS") && Sys.total_memory() < 24 * 1024^3
    ENV["JULIA_IMAGE_THREADS"] = "1"
end
println("Building standalone app with PackageCompiler.create_app()...")
println("  cpu_target=$(_CPU_TARGET), compress_sysimage=$(_COMPRESS_SYSIMAGE), JULIA_IMAGE_THREADS=$(get(ENV, "JULIA_IMAGE_THREADS", "default"))")
println("  This will take several minutes.")

create_app(
    _BUILD_PROJECT_DIR,
    _APP_DIR;
    executables = ["frdc-core" => "julia_main"],
    precompile_execution_file = _PRECOMPILE_SCRIPT,
    incremental = true,
    filter_stdlibs = false,
    force = true,
    c_driver_program = _C_DRIVER_PROGRAM,
    cpu_target = _CPU_TARGET,
    include_lazy_artifacts = false,
    include_transitive_dependencies = false,
    include_preferences = true,
    sysimage_build_args = `-O1 --strip-metadata`,
    compress_sysimage = _COMPRESS_SYSIMAGE,
)

